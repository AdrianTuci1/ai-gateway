#!/usr/bin/env bash
#
# render-backend.sh - write the S3 backend block for the edge environment.
#
# The state is shared by every run and by hand, so it cannot live in local
# files. Terraform backend blocks cannot read variables, so the block is
# generated here from the deploy environment that
# `load-deploy-env.sh` put in the process environment:
#
#   TF_STATE_BUCKET   bucket that holds the organization's Terraform state
#   AWS_REGION        region of the bucket and of the lock table
#   TF_STATE_KEY      key for this stack
#                     (default: ai-gateway/edge-lambda/terraform.tfstate)
#   TF_LOCK_TABLE     DynamoDB table used for locking (default: terraform-locks)
#
# The file is gitignored; `deploy/terraform/README.md` explains the bucket.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"
ENV_DIR="${ENV_DIR:-$REPO_ROOT/deploy/terraform/envs/edge-lambda}"

: "${TF_STATE_BUCKET:?TF_STATE_BUCKET is not set; run load-deploy-env.sh first}"
: "${AWS_REGION:?AWS_REGION is not set; run load-deploy-env.sh first}"

TF_STATE_KEY="${TF_STATE_KEY:-ai-gateway/edge-lambda/terraform.tfstate}"
TF_LOCK_TABLE="${TF_LOCK_TABLE:-terraform-locks}"

[ -d "$ENV_DIR" ] || { echo "render-backend.sh: no such directory: $ENV_DIR" >&2; exit 1; }

cat >"$ENV_DIR/backend.tf" <<EOF
# Generated by deploy/ci/render-backend.sh. Do not edit: the next run replaces it.
terraform {
  backend "s3" {
    bucket         = "$TF_STATE_BUCKET"
    key            = "$TF_STATE_KEY"
    region         = "$AWS_REGION"
    encrypt        = true
    dynamodb_table = "$TF_LOCK_TABLE"
  }
}
EOF

echo "backend: s3://$TF_STATE_BUCKET/$TF_STATE_KEY (lock: $TF_LOCK_TABLE)"
